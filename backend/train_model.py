# Sessions, not rows: each one yields SEQUENCE_LENGTH flush windows, so this
# is 250,000 extracted feature windows -- five times the old dataset -- of
# which the 25,000 final windows train the tabular models and all 250,000
# train the sequence model. Sized so a cold `docker-compose up` finishes
# training in a few minutes rather than ten.
# Overridable so CI can train a small model quickly. The default is what
# ships; anything smaller is for a smoke test, not for a real model.
N_SESSIONS = int(os.getenv("N_SESSIONS", "25000"))
HESITATION_THRESHOLD_MS = 400  # must match sdk/deepcheck.js's HESITATION_THRESHOLD_MS

# Mirrors sdk/deepcheck.js's default flush interval. One simulated session is
# SEQUENCE_LENGTH consecutive flushes, i.e. the same ~20 seconds of behavior
# the LSTM reads back out of Postgres at serving time. Before this, a
# "sequence" was ten jittered copies of a single instant, so the temporal
# model was fed no time information at all while carrying 30% of the
# ensemble weight.
FLUSH_INTERVAL_MS = 2000

# Fraction of each class simulated as the "other" persona -- sophisticated
# bots that mimic human timing (bot_sophisticated), and rushed/efficient
# humans that look more robotic (human_rushed). Without this, the two classes
# would be cleanly separable, which is a modeling smell, not a real result.
CONTAMINATION_RATE = 0.10

# Fraction of each class whose behavior CHANGES mid-session: human then
# robotic (labelled bot -- a session handed off to automation) and robotic
# then human (labelled human -- a script that warms up a page a real customer
# then uses). These are the samples that carry temporal information; without
# them the sequence model has nothing to learn that the aggregate row does
# not already say.
DRIFT_RATE = 0.12

SEED = 42
rng = np.random.default_rng(SEED)

# The forests take random_state=42, but NOTHING seeded torch. The LSTM's weight
# initialisation, its dropout masks and the batch shuffling below all drew from
# torch's global RNG, so every run of this script produced a different sequence
# model -- one carrying 30% of the ensemble weight. Two runs of "the same"
# pipeline disagreed by more than ten risk points on the same session, and the
# claim that the artifacts are reproducible from a fixed seed was true only of
# the forests. Retraining could therefore turn a detected bot into a merely
# "suspicious" one with no code change at all, which is precisely the kind of
# result nobody can defend.
torch.manual_seed(SEED)


def _hesitation_intervals(event_times: list[int], flush_checkpoint: int | None = None) -> list[int]:
    """Mirrors sdk/deepcheck.js's recordHesitation() + its flush-time idle
    check: gaps >= threshold between consecutive tracked events count, AND
    if the flush happens while the session has gone quiet since the last
    event, that trailing silence counts too. Without the trailing check, a
    burst of activity followed by pure idle time until the window closes was
    invisible to hesitation tracking on both the SDK and training-data
    sides -- fixing only one would reintroduce a train/serve mismatch."""
    ts = sorted(event_times)
    gaps = [b - a for a, b in zip(ts, ts[1:]) if (b - a) >= HESITATION_THRESHOLD_MS]
    if flush_checkpoint is not None and ts:
        trailing_gap = flush_checkpoint - ts[-1]
        if trailing_gap >= HESITATION_THRESHOLD_MS:
            gaps.append(trailing_gap)
    return gaps


class _Stream:
    """Mutable per-session generation state.

    One cursor (`t`) drives the sequential phases -- move the mouse, click,
    type, pause -- because that ordering is what produces natural hesitation
    gaps in the merged event stream. Running every channel in parallel
    instead would fill the timeline with keystrokes and erase the pauses
    entirely, collapsing tereddut_skoru toward zero for humans.
    """

    def __init__(self, base_t: int):
        self.t = base_t
        self.x = 200.0
        self.y = 200.0
        self.scroll_y = 0
        self.mouse: list[dict] = []
        self.clicks: list[dict] = []
        self.scrolls: list[dict] = []
        self.keys: list[dict] = []
        self.focus: list[float] = []
        self.times: list[int] = []

    def mouse_event(self, x: float, y: float, t: int) -> None:
        self.mouse.append({"x": x, "y": y, "t": t})
        self.times.append(t)

    def click_event(self, x: float, y: float, t: int) -> None:
        self.clicks.append({"x": x, "y": y, "t": t})
        self.times.append(t)

    def scroll_event(self, scroll_y: float, t: int) -> None:
        self.scrolls.append({"scrollY": scroll_y, "t": t})
        self.times.append(t)

    def key_event(self, t: int) -> None:
        self.keys.append({"t": t})
        self.times.append(t)


def _session_traits() -> dict:
    """Traits decided once for the whole session rather than per phase.

    A keyboard-only user does not click in one phase and start clicking in
    the next; a headless script does not grow a mouse halfway through. These
    have to be session-level, or the personas blur together across a 20s
    session in a way a single 10s window never exposed.
    """
    return {
        # Sometimes zero clicks for the entire session: a script that calls
        # form.submit(), or a real human navigating by Tab only. Without this,
        # tiklama_yogunlugu == 0.0 would never appear in training for any
        # persona, so the model would have to extrapolate that value.
        "zero_clicks": bool(rng.random() < 0.15),
        # Real users often fill a form almost entirely by typing, with little
        # or no mouse movement. Without human examples of sparse mouse data,
        # the model only ever sees that pattern from headless bots and learns
        # "no mouse data" as an almost-deterministic bot signature.
        "sparse_mouse": bool(rng.random() < 0.30),
        # Headless (no mouse/scroll dispatch at all) vs scripted-with-motion
        # (Selenium/Puppeteer-style synthetic mousemove and scroll).
        "headless": bool(rng.random() < 0.5),
        # bot_sophisticated's near-constant velocity, fixed per session.
        "vx": float(rng.uniform(2, 5)),
        "vy": float(rng.uniform(1, 3)),
    }


def _phase_human(s: _Stream, traits: dict) -> None:
    n_points = int(rng.integers(0, 3)) if traits["sparse_mouse"] else int(rng.integers(10, 40))
    for _ in range(n_points):
        s.x += rng.normal(6, 6)
        s.y += rng.normal(4, 5)
        s.t += int(rng.uniform(50, 150))
        s.mouse_event(s.x, s.y, s.t)
        if rng.random() < 0.05:  # natural pause while moving the mouse
            s.t += int(rng.uniform(400, 1200))

    n_clicks = 0 if traits["zero_clicks"] else int(rng.integers(1, 5))
    for _ in range(n_clicks):
        s.t += int(rng.uniform(300, 900))  # natural pause before clicking
        s.click_event(s.x, s.y, s.t)

    n_keys = int(rng.integers(15, 50))
    for _ in range(n_keys):
        s.t += int(rng.lognormal(mean=5.0, sigma=0.5))  # ~100-350ms, occasional longer pause
        s.key_event(s.t)

    if rng.random() < 0.35:
        for _ in range(int(rng.integers(2, 6))):
            s.scroll_y += int(rng.uniform(40, 150))
            s.t += int(rng.uniform(60, 180))
            s.scroll_event(s.scroll_y, s.t)

    if rng.random() < 0.15:
        s.focus.append(s.t + int(rng.uniform(500, 3000)))


def _phase_human_rushed(s: _Stream, traits: dict) -> None:
    # NOTE: with tighter dt (faster movement) but similar jitter magnitude to
    # "human", this persona's acceleration variance came out HIGHER than plain
    # "human" (median hit the 1.0 clip ceiling) when first tuned -- dt shrinks
    # the denominator twice (speed, then acceleration), amplifying rather than
    # smoothing. Slightly wider dt and slightly smaller jitter brings it to a
    # believable "efficient but still human" range.
    n_points = int(rng.integers(0, 3)) if traits["sparse_mouse"] else int(rng.integers(6, 15))
    for _ in range(n_points):
        s.x += rng.normal(6, 4)
        s.y += rng.normal(4, 3)
        s.t += int(rng.uniform(60, 120))
        s.mouse_event(s.x, s.y, s.t)

    # NOTE: this used to be uniform(150, 400) -- numpy's upper bound is
    # exclusive, so it could NEVER reach HESITATION_THRESHOLD_MS (400),
    # meaning 100% of human_rushed samples got hesitation_intervals=[].
    # Widened so some click gaps naturally cross the threshold, like a real
    # (just efficient) human would.
    n_clicks = 0 if traits["zero_clicks"] else int(rng.integers(1, 5))
    for _ in range(n_clicks):
        s.t += int(rng.uniform(150, 650))
        s.click_event(s.x, s.y, s.t)

    n_keys = int(rng.integers(10, 35))
    for _ in range(n_keys):
        s.t += int(rng.uniform(60, 150))
        s.key_event(s.t)

    if rng.random() < 0.15:
        s.t += int(rng.uniform(50, 200))
        s.scroll_y += int(rng.uniform(50, 300))
        s.scroll_event(s.scroll_y, s.t)


def _phase_bot(s: _Stream, traits: dict) -> None:
    headless = traits["headless"]

    if traits["zero_clicks"]:
        n_clicks = 0
    else:
        n_clicks = int(rng.integers(1, 3)) if headless else int(rng.integers(4, 10))
    for _ in range(n_clicks):
        s.click_event(300.0, 200.0, s.t)
        s.t += int(rng.integers(1, 5)) if headless else max(150 + int(rng.normal(0, 8)), 1)

    # Real automation is not always perfectly instant end to end: page loads,
    # API round trips, explicit sleep()s between scripted steps, or basic
    # rate-limit evasion delays are common. Without this, EVERY bot sample has
    # hesitation_intervals=[], which trains the model to treat "hesitation
    # exactly at the neutral fallback" as an almost-perfect bot fingerprint --
    # a single incidental pause at inference then flips the whole verdict.
    if rng.random() < 0.30:
        s.t += int(rng.uniform(400, 1100))

    n_keys = int(rng.integers(0, 20))
    for _ in range(n_keys):
        s.key_event(s.t)
        s.t += int(rng.integers(1, 5)) if headless else max(3 + int(rng.normal(0, 1)), 1)


def _phase_bot_sophisticated(s: _Stream, traits: dict) -> None:
    n_points = int(rng.integers(15, 30))
    for _ in range(n_points):
        # More jitter than the plain "bot" variant -- this persona is the
        # hard-to-detect, human-mimicking bot, so its acceleration profile
        # should land closer to human territory.
        s.x += traits["vx"] * 10 + rng.normal(0, 2.5)
        s.y += traits["vy"] * 10 + rng.normal(0, 1.8)
        s.t += max(80 + int(rng.normal(0, 7)), 1)  # mostly regular interval
        s.mouse_event(s.x, s.y, s.t)

    # Same rationale as the "bot" branch: an occasional realistic pause
    # between phases, so hesitation_intervals==[] cannot be a near-guaranteed
    # bot fingerprint.
    if rng.random() < 0.30:
        s.t += int(rng.uniform(400, 1100))

    n_clicks = 0 if traits["zero_clicks"] else int(rng.integers(2, 4))
    for _ in range(n_clicks):
        s.t += max(500 + int(rng.normal(0, 15)), 1)  # mostly evenly spaced
        s.click_event(s.x, s.y, s.t)

    n_keys = int(rng.integers(10, 30))
    for _ in range(n_keys):
        s.t += max(150 + int(rng.normal(0, 8)), 1)  # mostly too-regular typing interval
        s.key_event(s.t)


_PHASES = {
    "human": _phase_human,
    "human_rushed": _phase_human_rushed,
    "bot": _phase_bot,
    "bot_sophisticated": _phase_bot_sophisticated,
}


def _background_motion(s: _Stream, traits: dict, base_t: int) -> None:
    """The plain "bot" persona's synthetic mousemove and scroll.

    These run on their own cursors, in parallel with the click and key phase,
    because that is how a Selenium-style script actually behaves: the driver
    dispatches motion events while the scripted steps proceed. Small jitter
    rather than a mathematically perfect constant -- real scripted dispatch
    still carries OS and rendering timing noise, and an exact-zero variance
    would hand the model a single-feature fingerprint.
    """
    if traits["headless"]:
        return

    n_points = int(rng.integers(10, 20))
    x, y = 100.0, 100.0
    t = base_t
    for _ in range(n_points):
        x += 5.0 + rng.normal(0, 3.0)
        y += 2.0 + rng.normal(0, 2.2)
        t += max(80 + int(rng.normal(0, 10)), 1)
        s.mouse_event(x, y, t)

    n_scroll = int(rng.integers(4, 8))
    t = base_t
    for i in range(1, n_scroll + 1):
        t += max(90 + int(rng.normal(0, 6)), 1)
        s.scroll_event(50.0 * i, t)


def _simulate_window(persona: str, traits: dict, base_t: int) -> dict:
    """One flush payload: exactly what the SDK would POST at one tick.

    This is the unit the model is served, so it is the unit the model is
    trained on. Its content and its statistics are unchanged from when a
    training row was a single window -- what changed is that a session is now
    a *sequence* of these rather than one in isolation.
    """
    s = _Stream(base_t)
    _PHASES[persona](s, traits)

    if persona == "bot":
        _background_motion(s, traits, base_t)

    # Simulate the flush boundary itself: activity is often followed by real
    # idle time before the window closes (e.g. a fast burst of typing, then
    # nothing until the next flush fires). See _hesitation_intervals().
    flush_checkpoint = s.t
    if rng.random() < 0.40:
        flush_checkpoint = s.t + int(rng.uniform(400, 2000))

    return {
        "mouse_trajectory": s.mouse,
        "click_timing": s.clicks,
        "scroll_events": s.scrolls,
        "hesitation_intervals": _hesitation_intervals(s.times, flush_checkpoint),
        "focus_changes": s.focus,
        "key_events": s.keys,
    }


def _persona_at_step(persona: str, step: int) -> str:
    """Which persona is driving the session at flush `step`.

    A drift session behaves as one persona for its first half and another for
    its second. That change is the only thing in the training set a sequence
    model can learn and an aggregate row cannot represent, so it is what makes
    feeding the LSTM real history worth doing at all.
    """
    if persona == "drift_to_bot":
        return "human" if step < SEQUENCE_LENGTH // 2 else "bot_sophisticated"
    if persona == "drift_to_human":
        return "bot_sophisticated" if step < SEQUENCE_LENGTH // 2 else "human"
    return persona


def simulate_session_windows(persona: str, base_t: int) -> list[dict]:
    """A whole session as SEQUENCE_LENGTH consecutive flush payloads.

    Session-level traits (keyboard-only, sparse mouse, headless) are drawn
    once and held for every window: a real user does not stop being
    keyboard-only halfway through, and a headless script does not grow a
    mouse. That is what makes the ten windows a coherent session rather than
    ten unrelated samples.

    Known approximation: consecutive windows are drawn independently, while
    the real SDK ships a 10s ROLLING window every 2s, so two real consecutive
    flushes share most of their events and are far more correlated than two
    windows here. The marginal distribution of any single window is exactly
    the one the tabular models are calibrated on, which is the property worth
    protecting; the cost is that the LSTM sees noisier step-to-step variation
    in training than in production.
    """
    traits = _session_traits()
    return [
        _simulate_window(_persona_at_step(persona, step), traits, base_t + step * FLUSH_INTERVAL_MS)
        for step in range(SEQUENCE_LENGTH)
    ]


def _pick_persona(is_bot: int) -> str:
    if is_bot:
        if rng.random() < DRIFT_RATE:
            return "drift_to_bot"
        return "bot_sophisticated" if rng.random() < CONTAMINATION_RATE else "bot"
    if rng.random() < DRIFT_RATE:
        return "drift_to_human"
    return "human_rushed" if rng.random() < CONTAMINATION_RATE else "human"


def generate_synthetic_dataset(n_rows: int = N_SESSIONS):
    """Returns (X, sequences, y).

    X          -- the FINAL flush's features per session, the aggregate row
                  RandomForest and IsolationForest train on.
    sequences  -- all SEQUENCE_LENGTH flushes per session, the real time
                  series the LSTM trains on. Its last timestep is X's row.
    """
    is_bot = rng.integers(0, 2, size=n_rows)
    n_features = len(FEATURE_NAMES)
    X = np.empty((n_rows, n_features))
    sequences = np.empty((n_rows, SEQUENCE_LENGTH, n_features))

    for i in range(n_rows):
        base_t = 1_700_000_000_000 + int(rng.integers(0, 10**9))
        for step, payload in enumerate(simulate_session_windows(_pick_persona(is_bot[i]), base_t)):
            features = extract_features(payload)
            sequences[i, step] = [features[name] for name in FEATURE_NAMES]
        X[i] = sequences[i, -1]

    return X, sequences, is_bot


