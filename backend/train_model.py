# Real rows are vastly outnumbered by synthetic ones, so without a weight they
# would be rounding error. This makes the real set count for roughly as much in
# aggregate as the synthetic set, while keeping synthetic coverage of the
# personas the browser lab does not enumerate.
REAL_TELEMETRY_WEIGHT = 120.0

# Fraction of real RUNS -- not flushes -- held out for evaluation. Splitting by
# run matters: every flush from one browser session is correlated with its
# siblings, so a random per-flush split puts the same session on both sides and
# reports a number that will not reproduce on a fresh session.
REAL_HOLDOUT_FRACTION = 0.3


def load_real_telemetry(path: str = REAL_TELEMETRY_PATH):
    """Labelled real-browser telemetry, split by run.

    This is the answer to the project's oldest weakness: the models were
    trained entirely on personas written by the same author as the detector,
    so their separation was partly self-fulfilling. The browser lab showed
    what that costs -- the same evasive attack scored 88.9 (blocked) in the
    simulator and 36.5 (approved) through real Chromium, because the heaviest
    timing features are inverted between the two distributions.

    Returns (X_train, y_train, X_eval, y_eval, eval_scenarios) or None.
    """
    if not os.path.exists(path):
        return None
    with open(path, encoding="utf-8") as fh:
        payload = json.load(fh)
    samples = payload.get("samples", [])
    if not samples:
        return None

    # A capture taken before a feature was added cannot be blended: the vector
    # would be the wrong width, or worse, silently mis-ordered.
    missing = [s for s in samples if any(n not in s["features"] for n in FEATURE_NAMES)]
    if missing:
        print(
            f"  WARNING: {len(missing)}/{len(samples)} real rows predate the current "
            "feature set and are being skipped. Re-run lab/capture.py."
        )
        samples = [s for s in samples if all(n in s["features"] for n in FEATURE_NAMES)]
    if not samples:
        return None

    # Group by PERSON where one is recorded, falling back to the session and
    # then to the scenario. The unit of the split has to be whoever generated
    # the data: flushes within a sitting are correlated, and sittings by the
    # same person are correlated too. Split by session alone and one person
    # who contributed ten sittings lands on both sides, so the reported number
    # answers "does it recognise this person again" instead of "does it work
    # on somebody new" -- and only the second question justifies collecting
    # the data at all. record_session.py --person fills this in.
    def group_of(sample):
        return sample.get("person_id") or sample.get("run_id") or sample["scenario"]

    runs = sorted({group_of(s) for s in samples})
    holdout_rng = np.random.default_rng(1234)
    holdout_rng.shuffle(runs)
    holdout = set(runs[: max(1, int(len(runs) * REAL_HOLDOUT_FRACTION))])

    def vec(sample):
        return [sample["features"][name] for name in FEATURE_NAMES]

    train = [s for s in samples if group_of(s) not in holdout]
    evaluate = [s for s in samples if group_of(s) in holdout]
    if not train or not evaluate:
        return None

    return (
        np.array([vec(s) for s in train], dtype=float),
        np.array([s["label"] for s in train]),
        np.array([vec(s) for s in evaluate], dtype=float),
        np.array([s["label"] for s in evaluate]),
        [s["scenario"] for s in evaluate],
    )


def report_real_holdout(rf, scaler, X_eval, y_eval, scenarios):
    """Accuracy on held-out REAL browser runs, broken down by scenario.

    The aggregate number hides the only asymmetry that matters: blocking a
    legitimate keyboard-only user costs a sale and a support call, while
    missing one bot costs one fraudulent attempt.
    """
    if len(y_eval) == 0:
        return
    proba = rf.predict_proba(scaler.transform(X_eval))[:, 1]
    print("\nHeld-out REAL browser runs (never seen in training):")
    print(f"  {'scenario':<20}{'n':>5}{'mean p(bot)':>14}{'flagged >=0.5':>15}")
    for name in sorted(set(scenarios)):
        idx = [i for i, sc in enumerate(scenarios) if sc == name]
        p = proba[idx]
        flagged = 100.0 * float((p >= 0.5).mean())
        print(f"  {name:<20}{len(idx):>5}{p.mean():>14.3f}{flagged:>14.0f}%")
    human = proba[y_eval == 0]
    bot = proba[y_eval == 1]
    if len(human) and len(bot):
        fpr = 100.0 * float((human >= 0.5).mean())
        recall = 100.0 * float((bot >= 0.5).mean())
        print(f"  overall: false positives {fpr:.1f}%, bot recall {recall:.1f}%")


def compute_feature_scaling(n_sessions: int = SCALING_SESSIONS) -> dict:
    """Measures where each heavy-tailed feature actually lives, and returns the
    log10 endpoints used to map it onto 0..1.

    This exists because the previous hand-picked divisors were wrong by orders
    of magnitude, and clipping hid it: acceleration variance divided by 2.2e-6
    put every jittered pointer path -- human or bot -- at exactly 1.000, so the
    feature answered "does the pointer wobble?" and nothing else. Two pixels of
    gaussian noise was enough to flip it.

    Percentiles rather than min/max, so one freak session cannot set the scale
    for everything else. Deliberately spans BOTH classes: the useful resolution
    is in the range between robotic and human, and cutting the scale at the
    human 1st percentile would flatten every bot to zero and throw that away.

    Runs on RAW values, so unlike the neutral fallbacks it needs no fixed-point
    iteration -- nothing here depends on its own output.
    """
    samples = {name: [] for name in scorer.LOG_SCALED_FEATURES}
    for _ in range(n_sessions):
        base_t = 1_700_000_000_000 + int(rng.integers(0, 10**9))
        persona = _pick_persona(int(rng.integers(0, 2)))
        for payload in simulate_session_windows(persona, base_t):
            for name, value in scorer.extract_raw(payload).items():
                if name in samples and value is not None and np.isfinite(value):
                    samples[name].append(max(float(value), scorer.RAW_FLOOR))

    scaling = {}
    for name, values in samples.items():
        if len(values) < 50:
            scaling[name] = scorer.FEATURE_SCALING[name]
            print(f"  {name}: only {len(values)} samples, keeping fallback")
            continue
        logs = np.log10(np.asarray(values))
        lo, hi = float(np.percentile(logs, 1)), float(np.percentile(logs, 99))
        if hi - lo < 0.5:  # degenerate spread; widen so the feature stays usable
            mid = (hi + lo) / 2.0
            lo, hi = mid - 0.5, mid + 0.5
        scaling[name] = (round(lo, 3), round(hi, 3))
    return scaling


def converge_neutral_defaults() -> dict:
    """Finds neutral fallbacks that TRAINING AND SERVING BOTH USE.

    This has to be a fixed point, not a single calculation, and the reason is
    worth spelling out. A sparse flush -- no scroll, no mouse -- takes the
    fallback value for those features, so every such session in the training
    set sits at exactly the same coordinate. Thousands of identical points
    make a dense atom, and the forest learns sharp splits right next to it.
    Compute a new fallback from that dataset and ship it, and inference now
    places sparse sessions at a coordinate the training data never contained,
    on the far side of those splits. Measured cost of getting this wrong:
    RandomForest scored a headless bot at p(fraud) = 0.000.

    So: run a small pilot, derive the midpoints, feed them back into feature
    extraction, and repeat. The values that come out are the values the real
    dataset is then generated with, and they are what gets stored in the
    bundle -- one consistent set everywhere.
    """
    defaults = dict(scorer.NEUTRAL_DEFAULTS)
    for pass_index in range(PILOT_PASSES):
        X, _, y = generate_synthetic_dataset(PILOT_SESSIONS)
        defaults = compute_neutral_defaults(X, y)
        # extract_features() reads this dict whenever no bundle is loaded,
        # which is the case for the whole of training.
        scorer.NEUTRAL_DEFAULTS.update(defaults)
        print(f"  pilot {pass_index + 1}/{PILOT_PASSES}: {defaults}")
    return defaults


def compute_neutral_defaults(X: np.ndarray, y: np.ndarray) -> dict:
    """Midpoint between the human and bot means of each fallback feature.

    scorer.py uses these when a flush carries too little raw signal to compute
    a feature at all. Deriving them here rather than hand-writing them in
    scorer.py is the point: they track the training distribution automatically
    instead of drifting stale the next time a persona is retuned.
    """
    defaults = {}
    for name in scorer.NEUTRAL_FEATURES:
        idx = FEATURE_NAMES.index(name)
        human_mean = float(X[y == 0, idx].mean())
        bot_mean = float(X[y == 1, idx].mean())
        defaults[name] = round(float(np.clip((human_mean + bot_mean) / 2.0, 0.0, 1.0)), 3)
    return defaults


def train_tabular_models(X_train, y_train, X_test, y_test, sample_weight=None):
    scaler = StandardScaler()
    X_train_scaled = scaler.fit_transform(X_train)
    X_test_scaled = scaler.transform(X_test)

    # max_features caps how many of the 6 features each split can consider.
    # Left at sklearn's default ("sqrt" -> 2 of 6), a single near-perfectly
    # separable feature still gets picked at most splits it's eligible for,
    # so the forest ends up overwhelmingly dependent on whichever feature is
    # cleanest in the training data -- a single incidental miss on that one
    # feature at inference time then overrides all other signal. Allowing
    # more features per split forces trees to also learn from the rest.
    # min_samples_leaf forces each leaf to generalize over multiple samples
    # instead of memorizing narrow, overfit decision "islands" -- a gentler
    # smoothing than an earlier attempt at max_depth=8 + min_samples_leaf=15,
    # which over-corrected and hurt bot recall. This is a lighter touch.
    rf = RandomForestClassifier(
        n_estimators=200,
        max_depth=12,
        max_features=4,
        min_samples_leaf=5,
        random_state=42,
        n_jobs=-1,
    )
    rf.fit(X_train_scaled, y_train, sample_weight=sample_weight)

    y_pred = rf.predict(X_test_scaled)
    rf_acc = accuracy_score(y_test, y_pred)
    print(f"RandomForest test accuracy: {rf_acc:.4f}")
    print("\nClassification Report (RandomForest):")
    print(classification_report(y_test, y_pred, target_names=["Gerçek Kullanıcı", "Bot"], digits=4))

    # Isolation Forest trains only on human (non-fraud) behavior to flag anomalies
    human_only = X_train_scaled[y_train == 0]
    iso_forest = IsolationForest(
        n_estimators=200, contamination=0.05, random_state=42, n_jobs=-1
    )
    iso_forest.fit(human_only)

    return scaler, rf, iso_forest


def train_lstm(seq_train_np, y_train, seq_test_np, y_test, epochs: int = 8, batch_size: int = 256):
    """Trains on the real per-flush sequences from simulate_session_windows().

    Previously this tiled one aggregate row across all ten timesteps and
    added noise, so every "sequence" was ten copies of the same instant and
    the model could not learn anything time-shaped -- while still carrying
    30% of the ensemble weight.
    """
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")

    seq_train = torch.tensor(seq_train_np, dtype=torch.float32)
    seq_test = torch.tensor(seq_test_np, dtype=torch.float32)
    y_train_t = torch.tensor(y_train, dtype=torch.float32).unsqueeze(1)
    y_test_t = torch.tensor(y_test, dtype=torch.float32).unsqueeze(1)

    model = BehaviorLSTM().to(device)
    optimizer = torch.optim.Adam(model.parameters(), lr=1e-3)
    criterion = nn.BCELoss()

    n_train = seq_train.shape[0]
    for epoch in range(epochs):
        model.train()
        permutation = torch.randperm(n_train)
        epoch_loss = 0.0
        for i in range(0, n_train, batch_size):
            idx = permutation[i : i + batch_size]
            batch_x = seq_train[idx].to(device)
            batch_y = y_train_t[idx].to(device)

            optimizer.zero_grad()
            preds = model(batch_x)
            loss = criterion(preds, batch_y)
            loss.backward()
            optimizer.step()
            epoch_loss += loss.item() * batch_x.size(0)

        model.eval()
        with torch.no_grad():
            test_preds = model(seq_test.to(device))
            test_acc = ((test_preds > 0.5).float().cpu() == y_test_t).float().mean().item()
        print(f"LSTM epoch {epoch + 1}/{epochs} - loss: {epoch_loss / n_train:.4f} - test_acc: {test_acc:.4f}")

    return model


def main():
    # sklearn's classification_report carries Turkish class names, and a
    # Windows console defaults to cp1252, where "ı" is unencodable -- the
    # run died on a print() after the forest was already trained.
    try:
        sys.stdout.reconfigure(encoding="utf-8")
    except (AttributeError, OSError):
        pass

    print("Measuring raw feature distributions for normalization...")
    feature_scaling = compute_feature_scaling()
    # extract_features() reads this whenever no bundle is loaded, which is the
    # case for the whole of training, so the dataset below is generated with
    # exactly the scaling that will be stored and served.
    scorer.FEATURE_SCALING.update(feature_scaling)
    print(f"Feature scaling (log10 range): {feature_scaling}")

    print("Converging neutral fallback values...")
    neutral_defaults = converge_neutral_defaults()

    print(
        f"Generating {N_SESSIONS} synthetic sessions "
        f"({SEQUENCE_LENGTH} flushes each, "
        f"{SEQUENCE_LENGTH * FLUSH_INTERVAL_MS / 1000:.0f}s per session)..."
    )
    X, sequences, y = generate_synthetic_dataset()

    # Split on indices so the aggregate rows and their sequences stay aligned:
    # sequences[i] must remain the history whose last timestep is X[i].
    idx_train, idx_test = train_test_split(
        np.arange(len(y)), test_size=0.2, random_state=42, stratify=y
    )
    X_train, X_test = X[idx_train], X[idx_test]
    y_train, y_test = y[idx_train], y[idx_test]
    seq_train, seq_test = sequences[idx_train], sequences[idx_test]

    print(f"Neutral defaults in force: {neutral_defaults}")

    real = load_real_telemetry()
    if real is None:
        print(
            "\n" + "==================================================================" + "\n"
            f" UYARI: {REAL_TELEMETRY_PATH} bulunamadi.\n"
            " Model YALNIZCA SENTETIK VERIYLE egitiliyor. Simulator zamanlama"
            " ozelliklerinde yanlis isareti ogretir: ayni kacamak saldiri\n"
            " simulasyonda 88.9 (bloklandi), gercek Chromium uzerinden 36.5\n"
            " (onaylandi) aldi. Boyle egitilen model, yayinlanan degerlendirme"
            " sayilarinin tarif ettigi model DEGILDIR.\n"
            " Cozum: lab/capture.py calistirin veya REAL_TELEMETRY_PATH ayarlayin."
            + "\n" + "=================================================================="
        )
        X_fit, y_fit, weights = X_train, y_train, None
    else:
        X_real, y_real, X_real_eval, y_real_eval, real_eval_scenarios = real
        print(
            f"\nBlending {len(y_real)} real-browser rows into training "
            f"({len(y_real_eval)} held out by run)."
        )
        X_fit = np.vstack([X_train, X_real])
        y_fit = np.concatenate([y_train, y_real])
        weights = np.concatenate(
            [np.ones(len(y_train)), np.full(len(y_real), REAL_TELEMETRY_WEIGHT)]
        )

    print("Training RandomForest + IsolationForest...")
    scaler, rf, iso_forest = train_tabular_models(X_fit, y_fit, X_test, y_test, weights)
    human_calibration = []
    if real is not None:
        report_real_holdout(rf, scaler, X_real_eval, y_real_eval, real_eval_scenarios)
        # Scores the finished model gives to held-out REAL human sessions.
        # scorer's conformal guard uses these to refuse blocking on a score
        # that is unremarkable for a legitimate user. Held out by run, so the
        # calibration is not measuring sessions the forest was fitted on.
        human_rows = X_real_eval[y_real_eval == 0]
        if len(human_rows):
            proba = rf.predict_proba(scaler.transform(human_rows))[:, 1]
            human_calibration = [round(float(p) * 100.0, 2) for p in proba]
            floor = 1.0 / (len(human_calibration) + 1.0)
            print(
                f"Conformal calibration: {len(human_calibration)} held-out human scores, "
                f"smallest achievable p-value {floor:.3f} "
                f"(guard alpha {scorer.CONFORMAL_ALPHA})."
            )
            if floor > scorer.CONFORMAL_ALPHA:
                print(
                    "  NOTE: too few calibration humans to assert that alpha, so the guard "
                    "will soften every block. Capture more real sessions before relying on it."
                )

    print("Training LSTM on real flush sequences...")
    lstm = train_lstm(seq_train, y_train, seq_test, y_test)

    joblib.dump(
        {
            "scaler": scaler,
            "rf": rf,
            "iso_forest": iso_forest,
            "feature_names": FEATURE_NAMES,
            # Read back by scorer.ModelBundle, which refuses to load a pickle
            # written by a different scikit-learn rather than scoring with it
            # and hoping.
            "sklearn_version": sklearn.__version__,
            # Where each heavy-tailed feature actually lives, measured rather
            # than guessed. Serving must normalize exactly as training did.
            "feature_scaling": feature_scaling,
            "neutral_defaults": neutral_defaults,
            "human_calibration": human_calibration,
        },
        scorer.MODEL_PATH,
    )
    torch.save(lstm.state_dict(), scorer.LSTM_PATH)
    print(f"Saved {os.path.basename(scorer.MODEL_PATH)} and {os.path.basename(scorer.LSTM_PATH)}")


if __name__ == "__main__":
    main()
